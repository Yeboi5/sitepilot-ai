/**
 * Generates supabase/seed.sql from the TypeScript demo seed so the memory and
 * Supabase drivers share identical demonstration data.
 *   npx tsx scripts/gen-seed-sql.ts
 * Dates are relative to when this runs; regenerate before a demo.
 */
import { writeFileSync } from "node:fs";
import { CATEGORIES } from "../src/lib/domain/categories";
import { MemoryStore } from "../src/lib/store/memory";
import { seedDemoData } from "../src/lib/store/seed";
import { rowToDb, TABLE_MAP } from "../src/lib/store/supabase-mapping";
import type { TableName } from "../src/lib/store/types";

const PG_ARRAYS = new Set(["categories", "regions", "qualifications", "member_ids"]);
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

function literal(col: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "string") return q(v);
  if (Array.isArray(v) && PG_ARRAYS.has(col)) return `${q(`{${v.map((x) => `"${String(x).replace(/"/g, '\\"')}"`).join(",")}}`)}`;
  return `${q(JSON.stringify(v))}::jsonb`;
}

async function main() {
  const store = new MemoryStore();
  await seedDemoData(store);
  const out: string[] = [
    "-- GENERATED by scripts/gen-seed-sql.ts — do not edit by hand.",
    "-- DEMONSTRATION DATA ONLY: every person, business, offer and saving is fictional.",
    "begin;",
    "set constraints all deferred;",
  ];
  for (const c of CATEGORIES) {
    out.push(`insert into public.categories (id, name, definition) values (${q(c.id)}, ${q(c.name)}, ${q(JSON.stringify(c))}::jsonb) on conflict (id) do update set name = excluded.name, definition = excluded.definition;`);
  }
  const order: TableName[] = ["users", "businesses", "documents", "requests", "offers", "negotiations", "groups", "watches", "alerts", "expenses", "transactions", "ledger"];
  for (const t of order) {
    for (const row of await store.list(t)) {
      const db = rowToDb(row as unknown as Record<string, unknown>);
      const cols = Object.keys(db);
      out.push(`insert into public.${TABLE_MAP[t]} (${cols.join(", ")}) values (${cols.map((c) => literal(c, db[c])).join(", ")});`);
    }
  }
  out.push("commit;", "");
  writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
  console.log(`Wrote supabase/seed.sql (${out.length} lines). Demo document files must be uploaded to Storage separately (see README).`);
}

main();
