/**
 * Generates supabase/seed.sql from the TypeScript demo seed so the memory and
 * Supabase drivers share identical demonstration data.
 *   npx tsx scripts/gen-seed-sql.ts
 * Dates are relative to when this runs; regenerate before a demo.
 */
import { writeFileSync } from "node:fs";
import { CATEGORIES } from "../src/lib/domain/categories";
import { MemoryStore } from "../src/lib/store/memory";
import { DEMO_PASSWORD, seedDemoData } from "../src/lib/store/seed";
import { rowToDb, TABLE_MAP } from "../src/lib/store/supabase-mapping";
import type { TableName } from "../src/lib/store/types";

const PG_ARRAYS = new Set(["categories", "regions", "qualifications", "member_ids"]);
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

function literal(col: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "string") return q(v);
  if (Array.isArray(v) && PG_ARRAYS.has(col)) return `${q(`{${v.map((x) => `"${String(x).replace(/"/g, '\\"')}"`).join(",")}}`)}`;
  return `${q(JSON.stringify(v))}::jsonb`;
}

async function main() {
  const store = new MemoryStore();
  await seedDemoData(store);
  const out: string[] = [
    "-- GENERATED by scripts/gen-seed-sql.ts — do not edit by hand.",
    "-- DEMONSTRATION DATA ONLY: every person, business, offer and saving is fictional.",
    "-- Load ONLY into local or staging demo projects, never production.",
    "begin;",
    "set constraints all deferred;",
    "set local search_path = public, extensions;",
  ];
  for (const c of CATEGORIES) {
    out.push(`insert into public.categories (id, name, definition) values (${q(c.id)}, ${q(c.name)}, ${q(JSON.stringify(c))}::jsonb) on conflict (id) do update set name = excluded.name, definition = excluded.definition;`);
  }
  // Demo accounts are real Supabase Auth users (email pre-confirmed) so sign-in, sessions and RLS
  // are exercised exactly as for real users. The on_auth_user_created trigger creates profiles,
  // which the upserts below then complete.
  for (const u of await store.list("users")) {
    const meta = JSON.stringify({ name: u.name, role: u.role === "admin" ? "customer" : u.role, region: u.region, is_demo: true });
    out.push(
      `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token, reauthentication_token) values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)}, crypt(${q(DEMO_PASSWORD)}, gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', ${q(meta)}::jsonb, now(), now(), '', '', '', '', '', '', '', '');`,
      `insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at) values (${q(u.id)}, ${q(u.id)}, ${q(JSON.stringify({ sub: u.id, email: u.email, email_verified: true }))}::jsonb, 'email', now(), now(), now());`,
    );
  }
  const order: TableName[] = ["users", "businesses", "credentials", "documents", "requests", "offers", "negotiations", "groups", "watches", "alerts", "expenses", "transactions", "ledger"];
  for (const t of order) {
    for (const row of await store.list(t)) {
      const { passwordHash: _p, ...rest } = row as unknown as Record<string, unknown>;
      const db = rowToDb(rest);
      const cols = Object.keys(db);
      const values = cols.map((c) => literal(c, db[c])).join(", ");
      out.push(t === "users"
        ? `insert into public.profiles (${cols.join(", ")}) values (${values}) on conflict (id) do update set ${cols.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`).join(", ")};`
        : `insert into public.${TABLE_MAP[t]} (${cols.join(", ")}) values (${values});`);
    }
  }
  out.push("commit;", "");
  writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
  console.log(`Wrote supabase/seed.sql (${out.length} lines). Demo document files must be uploaded to Storage separately (see README).`);
}

main();
