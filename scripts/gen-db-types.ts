/**
 * Generates src/lib/supabase/database.types.ts from a migrated PostgreSQL database, in the
 * same shape as `supabase gen types typescript`. Use the Supabase CLI when it is available;
 * this exists so types can be regenerated in CI/containers without Docker.
 *
 *   TEST_DATABASE_URL=postgresql://… npx tsx scripts/gen-db-types.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { Client } from "pg";

const url = process.env.TEST_DATABASE_URL ?? "postgresql://postgres:postgres@localhost:5432/sitepilot_test";

const SCALARS: Record<string, string> = {
  uuid: "string",
  text: "string",
  varchar: "string",
  date: "string",
  timestamptz: "string",
  timestamp: "string",
  int2: "number",
  int4: "number",
  int8: "number",
  numeric: "number",
  float4: "number",
  float8: "number",
  bool: "boolean",
  jsonb: "Json",
  json: "Json",
  void: "undefined",
};

async function main() {
  const db = new Client({ connectionString: url });
  await db.connect();

  const enums = await db.query<{ name: string; labels: string[] }>(`
    select t.typname::text as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`);
  const enumNames = new Set(enums.rows.map((e) => e.name));

  const cols = await db.query<{
    table_name: string;
    column_name: string;
    udt_name: string;
    is_nullable: "YES" | "NO";
    has_default: boolean;
    is_generated: boolean;
  }>(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable,
           (c.column_default is not null or c.is_identity = 'YES') as has_default,
           (c.is_generated = 'ALWAYS' or c.identity_generation = 'ALWAYS') as is_generated
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`);

  const fks = await db.query<{
    name: string;
    table_name: string;
    columns: string[];
    ref_table: string;
    ref_columns: string[];
    is_one_to_one: boolean;
  }>(`
    select con.conname as name, rel.relname as table_name,
           array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k)::text[] as columns,
           ref.relname as ref_table,
           array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k)::text[] as ref_columns,
           exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
                   and (i.indkey::int2[])::int2[] @> con.conkey and array_length(i.indkey::int2[], 1) = array_length(con.conkey, 1)) as is_one_to_one
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid join pg_namespace n on n.oid = rel.relnamespace
    join pg_class ref on ref.oid = con.confrelid join pg_namespace rn on rn.oid = ref.relnamespace
    where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
    order by rel.relname, con.conname`);

  const fns = await db.query<{ name: string; args: string; returns: string; table_cols: { name: string; type: string }[] }>(`
    select p.proname as name, pg_get_function_arguments(p.oid) as args, t.typname as returns,
      -- "returns table (...)" columns, which the Supabase client returns as an array of rows
      coalesce((select json_agg(json_build_object('name', p.proargnames[i], 'type', (select typname from pg_type where oid = p.proallargtypes[i])) order by i)
                from generate_subscripts(p.proargmodes, 1) i where p.proargmodes[i] = 't'), '[]') as table_cols
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type t on t.oid = p.prorettype
    where n.nspname = 'public'
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by p.proname`);

  await db.end();

  const tsType = (udt: string): string => {
    if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
    if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
    return SCALARS[udt] ?? "unknown";
  };

  const tables = new Map<string, typeof cols.rows>();
  for (const c of cols.rows) {
    const list = tables.get(c.table_name) ?? [];
    list.push(c);
    tables.set(c.table_name, list);
  }

  const out: string[] = [];
  out.push("// Generated by scripts/gen-db-types.ts — do not edit by hand.");
  out.push("");
  out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
  out.push("");
  out.push("export type Database = {");
  out.push("  public: {");
  out.push("    Tables: {");
  for (const [table, columns] of tables) {
    const field = (c: (typeof columns)[number], mode: "row" | "insert" | "update") => {
      const t = tsType(c.udt_name) + (c.is_nullable === "YES" ? " | null" : "");
      if (mode === "row") return `          ${c.column_name}: ${t};`;
      if (c.is_generated) return `          ${c.column_name}?: never;`;
      const optional = mode === "update" || c.is_nullable === "YES" || c.has_default;
      return `          ${c.column_name}${optional ? "?" : ""}: ${t};`;
    };
    out.push(`      ${table}: {`);
    for (const [label, mode] of [["Row", "row"], ["Insert", "insert"], ["Update", "update"]] as const) {
      out.push(`        ${label}: {`);
      for (const c of columns) out.push(field(c, mode));
      out.push("        };");
    }
    out.push("        Relationships: [");
    for (const fk of fks.rows.filter((f) => f.table_name === table)) {
      out.push("          {");
      out.push(`            foreignKeyName: "${fk.name}";`);
      out.push(`            columns: [${fk.columns.map((c) => `"${c}"`).join(", ")}];`);
      out.push(`            isOneToOne: ${fk.is_one_to_one};`);
      out.push(`            referencedRelation: "${fk.ref_table}";`);
      out.push(`            referencedColumns: [${fk.ref_columns.map((c) => `"${c}"`).join(", ")}];`);
      out.push("          },");
    }
    out.push("        ];");
    out.push("      };");
  }
  out.push("    };");
  out.push("    Views: { [_ in never]: never };");
  out.push("    Functions: {");
  for (const fn of fns.rows) {
    const args = fn.args
      .split(",")
      .map((a) => a.trim())
      .filter(Boolean)
      .map((a) => {
        const [name, ...type] = a.split(/\s+/);
        const udt = type.join(" ").replace(/^public\./, "");
        const mapped = enumNames.has(udt) ? `Database["public"]["Enums"]["${udt}"]` : "string";
        return `${name}: ${mapped}`;
      });
    const returns = fn.table_cols.length ? `{ ${fn.table_cols.map((c) => `${c.name}: ${tsType(c.type)}`).join("; ")} }[]` : tsType(fn.returns);
    out.push(`      ${fn.name}: { Args: ${args.length ? `{ ${args.join("; ")} }` : "never"}; Returns: ${returns} };`);
  }
  out.push("    };");
  out.push("    Enums: {");
  for (const e of enums.rows) out.push(`      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};`);
  out.push("    };");
  out.push("    CompositeTypes: { [_ in never]: never };");
  out.push("  };");
  out.push("};");
  out.push("");
  out.push('type PublicSchema = Database["public"];');
  out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
  out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
  out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
  out.push('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];');
  out.push("");

  const target = path.resolve(__dirname, "../src/lib/supabase/database.types.ts");
  writeFileSync(target, out.join("\n"));
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
